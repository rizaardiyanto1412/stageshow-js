// Writes kit/icons.ts: every lucide icon as a component that renders an SVG
// string, with lucide-react's props (size, color, strokeWidth,
// absoluteStrokeWidth, className). Each export is marked pure, so a bundle
// keeps only the icons a scene uses. Run after changing the lucide version:
// npm run icons
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const lucide = require('lucide')
const { version } = require('lucide/package.json')

const names = Object.keys(lucide).filter((n) => /^[A-Z]/.test(n) && Array.isArray(lucide[n])).sort()
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
// Aliases share their icon's node: write each node once and point the aliases at it
const seen = new Map()
const lines = []
for (const name of names) {
  const children = JSON.stringify(lucide[name][2])
  if (seen.has(children)) {
    lines.push(`export const ${name} = ${seen.get(children)}`)
    continue
  }
  seen.set(children, name)
  lines.push(`export const ${name} = /* @__PURE__ */ icon('${kebab(name)}', ${children})`)
}

const out = `// Generated by scripts/gen-icons.mjs from lucide@${version}. Do not edit.
// Every lucide icon as a string component with lucide-react's props.
import { jsx, type Html, type Style } from './jsx-runtime'

type Node = [string, Record<string, string>][]

export interface LucideProps {
  size?: number | string
  color?: string
  strokeWidth?: number | string
  /** Keep the stroke the same on screen at any size: strokeWidth is scaled by 24 / size. */
  absoluteStrokeWidth?: boolean
  className?: string
  style?: Style | string
  fill?: string
  stroke?: string
  [attribute: \`data-\${string}\` | \`aria-\${string}\`]: unknown
}
export type LucideIcon = (props: LucideProps) => Html

function icon(name: string, node: Node): LucideIcon {
  const body = node.map(([tag, attrs]) => \`<\${tag}\${Object.entries(attrs).map(([k, v]) => \` \${k}="\${v}"\`).join('')}/>\`).join('')
  // As lucide-react: its defaults first, then any prop the caller passes (fill, stroke, data-*) over them
  return ({ size = 24, color = 'currentColor', strokeWidth = 2, absoluteStrokeWidth, className, ...rest }) =>
    jsx('svg', {
      xmlns: 'http://www.w3.org/2000/svg',
      width: size,
      height: size,
      viewBox: '0 0 24 24',
      fill: 'none',
      stroke: color,
      strokeWidth: absoluteStrokeWidth ? (Number(strokeWidth) * 24) / Number(size) : strokeWidth,
      strokeLinecap: 'round',
      strokeLinejoin: 'round',
      'aria-hidden': 'true',
      ...rest,
      className: \`lucide lucide-\${name}\${className ? \` \${className}\` : ''}\`,
      dangerouslySetInnerHTML: { __html: body },
    })
}

${lines.join('\n')}
`
writeFileSync(new URL('../kit/icons.ts', import.meta.url), out)
console.log(`kit/icons.ts: ${names.length} icons (${seen.size} drawings)`)
